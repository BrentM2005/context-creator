class I18n:
    def __init__(self):
        self.lang = "en"

    def set_lang(self, lang_code):
        if lang_code in TRANSLATIONS:
            self.lang = lang_code

    def tr(self, key):
        return TRANSLATIONS.get(self.lang, {}).get(key, TRANSLATIONS["en"].get(key, key))

